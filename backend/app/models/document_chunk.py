from datetime import datetime
from sqlalchemy import Column, Integer, String, Text, DateTime, ForeignKey
from sqlalchemy.orm import relationship
from backend.app.database import Base

class DocumentChunk(Base):
    """
    FR-010: Persistent Vector Storage and Document Chunks
    Stores segmented semantic passages and their 384-dimensional dense vector embeddings
    generated by BAAI/bge-small-en-v1.5.
    """
    __tablename__ = "document_chunks"

    id = Column(Integer, primary_key=True, index=True)
    document_id = Column(Integer, ForeignKey("unstructured_documents.id"), nullable=False, index=True)
    chunk_index = Column(Integer, nullable=False)

    # Fast filtering attributes (denormalized from document & metadata)
    ticker = Column(String(20), nullable=False, index=True)
    doc_type = Column(String(50), nullable=False, index=True)
    fiscal_period = Column(String(30), nullable=True, index=True)

    # Passage text and SHA-256 content hash for duplicate suppression
    chunk_text = Column(Text, nullable=False)
    chunk_hash = Column(String(64), nullable=False, index=True)

    # Dense vector embedding (serialized JSON array of 384 floats)
    embedding_json = Column(Text, nullable=False)

    # Preserved multi-attribute metadata (FR-013: source, date, industry, geography, confidence_score)
    metadata_json = Column(Text, nullable=False)

    created_at = Column(DateTime, default=datetime.utcnow)

    # Relationship
    document = relationship("UnstructuredDocument", backref="chunks")
